#!/usr/bin/env python3
"""
mkpsgtab.py - VERA PSG frequency tables for psgrmt.s

    python3 mkpsgtab.py psgtab.s                        # every table (libvera)
    python3 mkpsgtab.py psgtab.s --std pal --rmt song.rmt   # only what a song uses

VERA PSG frequency word (16 bit):  f = word * (25 MHz / 512) / 2^17
so  word = f * 2^17 * 512 / 25e6 = f * 2.68435456.

A POKEY channel whose divider is n machine cycles gives f = CPU / (m * n),
m depending on the kind of sound, hence

    word = K / n,   K = CPU * 2.68435456 / m

    k  kind                       m
    0  pure tone                  2   (output toggles every n cycles)
    1  distortion C (poly4)       3   \\ period of poly4 sampled every n
    2                             5   |  cycles: 15 / gcd(n mod 15, 15);
    3                            15   /  n mod 15 = 0 -> silent
    4  poly5 tone                31
    5  poly17 noise               1   (VERA noise takes a new random value
    6  poly5 noise                2    once per period, POKEY noise can
                                       change every n cycles)

64 kHz 8 bit channels (n = 28 * (AUDF + 1)) are the usual case: their word
depends only on AUDF and on the kind, so it is read from a table:

    table kind 0 pure, 1 distortion C (via n mod 15), 2 poly5 tone,
               3 poly17 noise, 4 poly5 noise

Words above 65535 (above ~24.4 kHz) are clamped; 0 means silent.

A table is 2 pages (low and high bytes of the word), 20 pages for every
standard and kind (5 KB).  --std (the TV standard of the songs: psgrmt.s
follows rmt_palnts, the song's, not the machine's) and --kinds / --rmt
(the kinds the instruments of a song use) keep only some of them; the
others are mapped to a table that exists (the other standard, else the pure
tone), so a missing one plays at a wrong pitch instead of crashing.

Output (ca65):
    segment PSGTAB (page aligned): psgtab_lo pages, then psgtab_hi pages
    segment RODATA: psgtab_map_lo, psgtab_map_hi: [std * 5 + kind] = the
                    page (high byte of the address) of that table, std 0 =
                    PAL, 1 = NTSC; psg_ktab: K, 24 bit little endian,
                    (std * 7 + k) * 3
"""
import argparse
import math
import struct

CPU = {0: 1773447, 1: 1789773}          # PAL, NTSC machine clock (Hz)
SCALE = 2 ** 17 * 512 / 25e6           # VERA word per Hz
KM = [2, 3, 5, 15, 31, 1, 2]            # m for k = 0..6
# AUDC >> 5 (distortion) -> table kind, as dist_sk in psgrmt.s
DIST_KIND = [4, 2, 4, 2, 3, 0, 1, 0]
# RMT instrument distortion (envelope byte 2, bits 1-3) -> AUDC >> 5:
# 3 is the 16 bit bass and 7 the second bass table, both distortion C
RMT_DIST = [0, 1, 2, 6, 4, 5, 6, 6]


def k_const(std, k):
    return round(CPU[std] * SCALE / KM[k])


def word(std, kind, audf):
    n = 28 * (audf + 1)
    if kind == 1:
        r = n % 15
        if r == 0:
            return 0
        m = 15 // math.gcd(r, 15)
    else:
        m = {0: 2, 2: 31, 3: 1, 4: 2}[kind]
    return min(65535, round(CPU[std] * SCALE / m / n))


def rmt_kinds(path):
    """table kinds used by the instruments of an RMT module"""
    d = open(path, 'rb').read()
    a = struct.unpack_from('<H', d, 2)[0]
    body = d[6:]
    instr, tlo = struct.unpack_from('<2H', body, 8)
    kinds = set()
    for i in range((tlo - instr) // 2):
        p = struct.unpack_from('<H', body, instr - a + 2 * i)[0]
        if p == 0:
            continue
        ins = body[p - a:]
        for e in range(ins[0] + 1, ins[2] + 1, 3):     # envelope: 3 bytes an entry
            kinds.add(DIST_KIND[RMT_DIST[(ins[e + 1] >> 1) & 7]])
    return kinds


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('out')
    ap.add_argument('--std', choices=('pal', 'ntsc', 'both'), default='both')
    ap.add_argument('--kinds', help='table kinds to keep, e.g. 0,1 (default: all)')
    ap.add_argument('--rmt', action='append', default=[],
                    help='keep the kinds the instruments of this RMT module use (repeatable)')
    a = ap.parse_args()

    stds = {'pal': [0], 'ntsc': [1], 'both': [0, 1]}[a.std]
    kinds = set(range(5))
    if a.kinds or a.rmt:
        kinds = set(int(k) for k in a.kinds.split(',')) if a.kinds else set()
        for r in a.rmt:
            kinds |= rmt_kinds(r)
    kinds.add(0)                                   # the fallback: pure tone
    have = [(s, k) for s in stds for k in sorted(kinds)]
    page = {sk: i for i, sk in enumerate(have)}

    def table(s, k):                               # the table that plays (s, k)
        for c in ((s, k), (1 - s, k), (s, 0), (1 - s, 0)):
            if c in page:
                return page[c]

    vals = [word(s, k, x) for s, k in have for x in range(256)]
    out = ["; generated by tools/mkpsgtab.py - do not edit",
           "; VERA PSG frequency words for POKEY 64 kHz 8 bit channels",
           "; tables (std, kind): " + " ".join("%s/%d" % ("PAL" if s == 0 else "NTSC", k) for s, k in have),
           "        .export psgtab_lo, psgtab_hi, psgtab_map_lo, psgtab_map_hi, psg_ktab",
           '        .segment "PSGTAB"',
           "psgtab_lo:"]
    for i in range(0, len(vals), 16):
        out.append("        .byte " + ",".join("$%02X" % (v & 0xFF) for v in vals[i:i + 16]))
    out.append("psgtab_hi:")
    for i in range(0, len(vals), 16):
        out.append("        .byte " + ",".join("$%02X" % (v >> 8) for v in vals[i:i + 16]))
    out.append('        .segment "RODATA"')
    out.append("; [std * 5 + kind] -> page of its table")
    out.append("psgtab_map_lo:")
    out.append("        .byte " + ", ".join(">(psgtab_lo + %d * 256)" % table(s, k)
                                            for s in (0, 1) for k in range(5)))
    out.append("psgtab_map_hi:")
    out.append("        .byte " + ", ".join(">(psgtab_hi + %d * 256)" % table(s, k)
                                            for s in (0, 1) for k in range(5)))
    out.append("; K = CPU * 2^17 * 512 / 25e6 / m, (std * 7 + k) * 3, 24 bit")
    out.append("psg_ktab:")
    for s in (0, 1):
        out.append("        .faraddr " + ", ".join(str(k_const(s, k)) for k in range(7)))
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
